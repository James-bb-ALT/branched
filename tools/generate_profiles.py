def profile(species, archetype, logs, leaves, sapling, height, radius, bend,
            branches, depth, angle, ratio, asymmetry, pattern, crown_width,
            crown_density, clusters, segments, max_leaves, quads, compatibility,
            source, biomes, wood=None, fruit=False, notes=None, version=1):
    data = {
        "schema": 1,
        "species": species,
        "archetype": archetype,
        "logs": logs,
        "leaves": leaves,
    }
    if wood:
        data["wood"] = wood
    if sapling:
        data["sapling"] = sapling
    data.update({
        "trunk": {"height": height, "radius": radius, "bend": bend},
        "branches": {
            "primaryCount": branches,
            "depth": depth,
            "angleDegrees": angle,
            "lengthRatio": ratio,
            "asymmetry": asymmetry,
            "pattern": pattern,
        },
        "crown": {
            "widthRatio": crown_width,
            "density": crown_density,
            "clusterCount": clusters,
        },
        "generation": {"mode": "semiprocedural_once", "attempts": 3, "version": version},
        "budget": {"maxSegments": segments, "maxLeaves": max_leaves, "maxQuads": quads},
        "compatibility": compatibility,
        "source": {"feature": source},
        "biomes": biomes,
        "fruitBearing": fruit,
    })
    if notes:
        data["notes"] = notes
    return data


